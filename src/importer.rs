/// Administrators predate the normalized role tables. Preserve the authority
/// that migration 010 granted them.
async fn backfill_owner_roles(target: &mut sqlx::PgConnection) -> anyhow::Result<u64> {
    let result = sqlx::query(
        "INSERT INTO user_roles(user_id,role_name,granted_by_user_id,created_at) \
         SELECT id, 'owner', NULL, created_at FROM users WHERE is_admin \
         ON CONFLICT (user_id, role_name) DO NOTHING",
    )
    .execute(&mut *target)
    .await?;
    Ok(result.rows_affected())
}

/// Advance identity sequences past the imported identifiers.
async fn reset_sequences(target: &mut sqlx::PgConnection) -> anyhow::Result<()> {
    for table in IDENTITY_TABLES {
        let sql = format!(
            "SELECT setval(pg_get_serial_sequence('{table}','id'), \
             COALESCE((SELECT MAX(id) FROM {table}), 0) + 1, false)"
        );
        sqlx::query(&sql).execute(&mut *target).await?;
    }
    Ok(())
}

#[tokio::main]
async fn main() -> anyhow::Result<()> {
    let options = parse_options()?;
    let target_label = veil_forum::store::redact_database_url(&options.database_url);

    let source = SqlitePoolOptionsT::new()
        .max_connections(1)
        .connect_with(
            SqliteConnectOptions::from_str(&format!("sqlite:{}", options.sqlite_path))?
                .read_only(true),
        )
        .await
        .with_context(|| format!("open SQLite database {}", options.sqlite_path))?;

    // Read (and validate) every timestamp before touching the target, so a
    // malformed row cannot leave a half-imported database behind.
    let mut expected: Vec<(&str, i64)> = Vec::new();
    for table in TABLES {
        if *table == "sessions" && !options.include_sessions {
            continue;
        }
        expected.push((table, count_rows_sqlite(&source, table).await?));
    }
    println!("Source: {}", options.sqlite_path);
    for (table, count) in &expected {
        println!("  {table:<18} {count}");
    }

    let target = PgPool::connect(&options.database_url)
        .await
        .with_context(|| format!("connect to PostgreSQL at {target_label}"))?;
    sqlx::migrate!("./migrations")
        .run(&target)
        .await
        .context("apply PostgreSQL migrations")?;

    if options.dry_run {
        let has_data = target_has_data(&target).await?;
        println!(
            "Dry run: target {} and {}",
            target_label,
            if has_data {
                "already contains forum data (--force would truncate it)"
            } else {
                "is empty"
            }
        );
        return Ok(());
    }

    // Everything that writes to the target happens in one transaction. A
    // malformed legacy row (a unique violation, a foreign key, a failed role
    // check) must roll the whole import back instead of leaving a truncated,
    // half-populated database behind.
    let mut tx = target.begin().await?;

    if target_has_data(&target).await? {
        if !options.force {
            anyhow::bail!(
                "target {target_label} already contains forum data; \
                 re-run with --force to replace it (existing rows are deleted)"
            );
        }
        println!("--force: clearing existing forum data in {target_label}");
        truncate_forum_tables(&mut tx).await?;
    } else {
        // Seed rows must not collide with imported rows.
        sqlx::query("TRUNCATE configs, roles CASCADE")
            .execute(&mut *tx)
            .await?;
        sqlx::query("INSERT INTO roles(name) VALUES ('owner'), ('admin'), ('moderator')")
            .execute(&mut *tx)
            .await?;
    }

    import_users(&source, &mut tx).await?;
    import_boards(&source, &mut tx).await?;
    import_configs(&source, &mut tx).await?;
    import_invite_codes(&source, &mut tx).await?;
    import_threads(&source, &mut tx).await?;
    import_posts(&source, &mut tx).await?;
    if options.include_sessions {
        import_sessions(&source, &mut tx).await?;
    }
    import_audit_logs(&source, &mut tx).await?;
    import_user_roles(&source, &mut tx).await?;
    import_board_moderators(&source, &mut tx).await?;
    import_reports(&source, &mut tx).await?;

    let granted = backfill_owner_roles(&mut tx).await?;
    if granted > 0 {
        println!("Restored owner role for {granted} administrator account(s)");
    }
    reset_sequences(&mut tx).await?;
    tx.commit().await?;

    // Statistics are collected after the rows are durable.
    sqlx::raw_sql("ANALYZE").execute(&target).await?;

    let mut failures = Vec::new();
    println!("Reconciliation:");
    for (table, expected_count) in &expected {
        let actual = count_rows_postgres(&target, table).await?;
        let ok = actual == *expected_count;
        println!(
            "  {:<18} source {:<8} target {:<8} {}",
            table,
            expected_count,
            actual,
            if ok { "ok" } else { "MISMATCH" }
        );
        if !ok {
            failures.push(*table);
        }
    }
    if !failures.is_empty() {
        anyhow::bail!("row counts differ for: {}", failures.join(", "));
    }

    println!("Import complete. Start veil-forum with:");
    println!("  veil-forum --database-url {}", target_label);
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_every_historical_timestamp_format() {
        // RFC3339 with nanoseconds and with offsets: every variant must resolve
        // to the same UTC instant, keeping the nanosecond precision.
        for (input, nanos) in [
            ("2026-08-26T08:19:02.853853123Z", 853_853_123),
            ("2026-08-26T08:19:02.123456Z", 123_456_000),
            ("2026-08-26T16:19:02.123456789+08:00", 123_456_789),
            ("2026-08-26T03:19:02.123456789-05:00", 123_456_789),
        ] {
            let parsed = parse_legacy_time(input).unwrap_or_else(|e| panic!("{input}: {e}"));
            let expected = format!("2026-08-26T08:19:02.{nanos:09}Z")
                .parse::<DateTime<Utc>>()
                .expect("expected instant");
            assert_eq!(parsed, expected, "{input}");
            assert_eq!(
                parsed.timestamp_nanos_opt().unwrap() % 1_000_000_000,
                nanos,
                "{input}"
            );
        }

        // Second precision, zero-nanosecond and legacy space-separated forms.
        let reference = "2026-08-26T08:19:02Z"
            .parse::<DateTime<Utc>>()
            .expect("instant");
        let seconds = parse_legacy_time("2026-08-26T08:19:02Z").expect("rfc3339 seconds");
        assert_eq!(seconds, reference);
        let zero_nanos = parse_legacy_time("2026-08-26T08:19:02.000000000Z").expect("zero nanos");
        assert_eq!(zero_nanos, reference);
        let legacy = parse_legacy_time("2026-08-26 08:19:02").expect("legacy format");
        assert_eq!(legacy, reference);
        let legacy_nanos =
            parse_legacy_time("2026-08-26 08:19:02.500000000").expect("legacy with nanos");
        assert_eq!(
            legacy_nanos.timestamp_nanos_opt().unwrap() % 1_000_000_000,
            500_000_000
        );
    }

    #[test]
    fn normalizes_offsets_to_utc() {
        let expected = "2026-08-26T08:19:02.123456789Z"
            .parse::<DateTime<Utc>>()
            .unwrap();
        for offset in ["Z", "+00:00", "-05:00", "+05:30", "+08:00", "-12:00"] {
            let shifted = match offset {
                "Z" | "+00:00" => "2026-08-26T08:19:02.123456789Z".to_string(),
                "-05:00" => "2026-08-26T03:19:02.123456789-05:00".to_string(),
                "+05:30" => "2026-08-26T13:49:02.123456789+05:30".to_string(),
                "+08:00" => "2026-08-26T16:19:02.123456789+08:00".to_string(),
                "-12:00" => "2026-08-25T20:19:02.123456789-12:00".to_string(),
                _ => unreachable!(),
            };
            let parsed = parse_legacy_time(&shifted).expect("valid offset");
            assert_eq!(parsed, expected, "offset {offset}");
        }
    }

    #[test]
    fn rejects_invalid_timestamps() {
        for input in ["", "not-a-timestamp", "2026-13-45T99:99:99Z", "26/08/2026"] {
            assert!(
                parse_legacy_time(input).is_err(),
                "{input:?} must be rejected"
            );
        }
    }
}

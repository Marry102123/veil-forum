//! One-shot SQLite to PostgreSQL importer.
//!
//! This is the only target that links the SQLite driver; the server binary
//! talks to PostgreSQL exclusively. It is meant to run once per installation
//! during the upgrade to the PostgreSQL backend:
//!
//! ```text
//! veil-forum-import --sqlite /var/lib/veil-forum/forum.db \
//!                   --database-url postgres:///veil_forum?host=/var/run/postgresql
//! ```
//!
//! Behaviour:
//!   * The PostgreSQL schema is created by the embedded migrations when missing.
//!   * Rows are copied with their original identifiers, in foreign-key order.
//!   * Timestamps are parsed from every historical SQLite text format and stored
//!     as `TIMESTAMPTZ`.
//!   * Identity sequences are advanced past the imported identifiers, so new
//!     rows continue where the old database stopped.
//!   * A per-table row-count reconciliation runs at the end; any mismatch is a
//!     hard error.
//!
//! Safety:
//!   * The source SQLite file is opened read-only and never modified.
//!   * The target is only written when it has no forum data, or when `--force`
//!     is passed (which truncates the forum tables first).
//!   * `--dry-run` reports what would be copied and exits.


/// Parse every timestamp format historical SQLite databases contain:
/// RFC3339 with nanoseconds, RFC3339 with offsets, second precision, the
/// space-separated legacy form, and both with or without a trailing `Z`.
pub fn parse_legacy_time(value: &str) -> anyhow::Result<DateTime<Utc>> {
    let s = value.trim();
    if let Ok(dt) = DateTime::parse_from_rfc3339(s) {
        return Ok(dt.with_timezone(&Utc));
    }
    for format in [
        "%Y-%m-%dT%H:%M:%S%.fZ",
        "%Y-%m-%dT%H:%M:%SZ",
        "%Y-%m-%d %H:%M:%S%.f",
        "%Y-%m-%d %H:%M:%S",
        "%Y-%m-%d %H:%M:%S%.fZ",
        "%Y-%m-%d %H:%M:%SZ",
    ] {
        if let Ok(dt) = NaiveDateTime::parse_from_str(s, format) {
            return Ok(dt.and_utc());
        }
    }
    Err(anyhow::anyhow!("invalid timestamp: {value:?}"))
}

struct Options {
    sqlite_path: String,
    database_url: String,
    dry_run: bool,
    force: bool,
    include_sessions: bool,
}

fn parse_options() -> anyhow::Result<Options> {
    let mut sqlite_path = None;
    let mut database_url = std::env::var("DATABASE_URL").ok();
    let mut dry_run = false;
    let mut force = false;
    let mut include_sessions = false;
    let mut args = std::env::args().skip(1);
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--sqlite" => {
                sqlite_path = Some(
                    args.next()
                        .context("--sqlite requires a path to the SQLite database")?,
                )
            }
            "--database-url" => {
                database_url = Some(
                    args.next()
                        .context("--database-url requires a connection string")?,
                )
            }
            "--dry-run" => dry_run = true,
            "--force" => force = true,
            "--include-sessions" => include_sessions = true,
            "--help" | "-h" => {
                println!(
                    "usage: veil-forum-import --sqlite PATH [--database-url URL] [--dry-run] [--force] [--include-sessions]"
                );
                std::process::exit(0);
            }
            other => anyhow::bail!("unknown argument {other:?}; try --help"),
        }
    }
    Ok(Options {
        sqlite_path: sqlite_path.context("--sqlite PATH is required")?,
        database_url: database_url
            .unwrap_or_else(|| "postgres:///veil_forum?host=/var/run/postgresql".to_string()),
        dry_run,
        force,
        include_sessions,
    })
}

// Every accessor decodes `Option<T>`: the SQLite driver maps NULL to a zero
// value when a bare integer is requested, which would turn a nullable foreign
// key such as `deleted_by_user_id` into 0 and break the copy.

/// SQLite stores booleans as 0/1 and may return them as either integer or text.
fn bool_at(row: &sqlx::sqlite::SqliteRow, name: &str) -> bool {
    if let Some(value) = row.try_get::<Option<i64>, _>(name).ok().flatten() {
        return value != 0;
    }
    row.try_get::<Option<String>, _>(name)
        .ok()
        .flatten()
        .map(|value| value != "0" && !value.is_empty())
        .unwrap_or(false)
}

fn i64_at(row: &sqlx::sqlite::SqliteRow, name: &str) -> Option<i64> {
    row.try_get::<Option<i64>, _>(name).ok().flatten()
}

fn string_at(row: &sqlx::sqlite::SqliteRow, name: &str) -> Option<String> {
    row.try_get::<Option<String>, _>(name).ok().flatten()
}

fn time_at(row: &sqlx::sqlite::SqliteRow, name: &str) -> anyhow::Result<Option<DateTime<Utc>>> {
    match string_at(row, name) {
        Some(value) if !value.trim().is_empty() => Ok(Some(
            parse_legacy_time(&value).with_context(|| format!("column {name}"))?,
        )),
        _ => Ok(None),
    }
}

async fn count_rows_sqlite(pool: &sqlx::SqlitePool, table: &str) -> anyhow::Result<i64> {
    let sql = format!("SELECT COUNT(*) FROM {table}");
    Ok(sqlx::query_scalar::<_, i64>(&sql).fetch_one(pool).await?)
}

async fn count_rows_postgres(pool: &PgPool, table: &str) -> anyhow::Result<i64> {
    let sql = format!("SELECT COUNT(*) FROM {table}");
    Ok(sqlx::query_scalar::<_, i64>(&sql).fetch_one(pool).await?)
}

async fn target_has_data(pool: &PgPool) -> anyhow::Result<bool> {
    let users: i64 = sqlx::query_scalar("SELECT COUNT(*) FROM users")
        .fetch_one(pool)
        .await?;
    if users > 0 {
        return Ok(true);
    }
    let posts: i64 = sqlx::query_scalar("SELECT COUNT(*) FROM posts")
        .fetch_one(pool)
        .await?;
    Ok(posts > 0)
}

async fn truncate_forum_tables(target: &mut sqlx::PgConnection) -> anyhow::Result<()> {
    sqlx::raw_sql(
        "TRUNCATE users, boards, configs, invite_codes, threads, posts, sessions, \
         audit_logs, user_roles, board_moderators, reports RESTART IDENTITY CASCADE",
    )
    .execute(&mut *target)
    .await?;
    Ok(())
}

async fn import_users(
    source: &sqlx::SqlitePool,
    target: &mut sqlx::PgConnection,
) -> anyhow::Result<u64> {
    let rows = sqlx::query("SELECT * FROM users").fetch_all(source).await?;
    let mut copied = 0u64;
    for row in &rows {
        sqlx::query(
            "INSERT INTO users(id,username,password_hash,is_admin,is_banned,created_at,locale) \
             VALUES($1,$2,$3,$4,$5,$6,$7)",
        )
        .bind(i64_at(row, "id"))
        .bind(string_at(row, "username").unwrap_or_default())
        .bind(string_at(row, "password_hash").unwrap_or_default())
        .bind(bool_at(row, "is_admin"))
        .bind(bool_at(row, "is_banned"))
        .bind(time_at(row, "created_at")?.unwrap_or_else(Utc::now))
        .bind(string_at(row, "locale").unwrap_or_else(|| "zh".to_string()))
        .execute(&mut *target)
        .await?;
        copied += 1;
    }
    Ok(copied)
}

